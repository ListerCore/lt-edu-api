// Gateway is the REST handler plus the connection it holds to the gRPC server
type Gateway struct {
	http.Handler
	conn *gogrpc.ClientConn
}

// Close releases the connection to the gRPC server
func (g *Gateway) Close() error { return g.conn.Close() }

// New builds the gateway against the gRPC server at grpcAddr (the API's own port on the loopback)
func New(ctx context.Context, grpcAddr string, logger zerolog.Logger) (*Gateway, error) {
	conn, err := gogrpc.NewClient(grpcAddr, gogrpc.WithTransportCredentials(insecure.NewCredentials()))
	if err != nil {
		return nil, err
	}

	mux := runtime.NewServeMux(
		// Same JSON as the rest of the HTTP API: proto (snake_case) names and every field present
		runtime.WithMarshalerOption(runtime.MIMEWildcard, &runtime.JSONPb{
			MarshalOptions:   protojson.MarshalOptions{UseProtoNames: true, EmitUnpopulated: true},
			UnmarshalOptions: protojson.UnmarshalOptions{DiscardUnknown: true},
		}),
		runtime.WithIncomingHeaderMatcher(headerMatcher),
		runtime.WithErrorHandler(errorHandler(logger)),
	)

	registers := []func(context.Context, *runtime.ServeMux, *gogrpc.ClientConn) error{
		academicv1.RegisterAcademicServiceHandler,
		institutionv1.RegisterInstitutionServiceHandler,
		peoplev1.RegisterPeopleServiceHandler,
		attendancev1.RegisterAttendanceServiceHandler,
		assessmentv1.RegisterAssessmentServiceHandler,
		assessmentv1.RegisterClosingServiceHandler,
	}
	for _, register := range registers {
		if err := register(ctx, mux, conn); err != nil {
			_ = conn.Close()
			return nil, err
		}
	}
	return &Gateway{Handler: detach(mux), conn: conn}, nil
}

// detach hands the gateway a request that owns its memory. Fiber's adaptor builds r.Header and r.URL as views
// over fasthttp buffers that are reused by the next request; the gRPC client keeps header values in its HPACK
// table, so without this copy a later call could go out with an earlier call's Authorization (another user's
// session, even another institution's)
func detach(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		owned := r.Clone(r.Context())
		owned.Header = make(http.Header, len(r.Header))
		for key, values := range r.Header {
			copied := make([]string, len(values))
			for i, v := range values {
				copied[i] = strings.Clone(v)
			}
			owned.Header[strings.Clone(key)] = copied
		}
		if u, err := url.Parse(strings.Clone(r.URL.String())); err == nil {
			owned.URL = u
		}
		owned.RequestURI = strings.Clone(r.RequestURI)
		owned.Host = strings.Clone(r.Host)
		owned.RemoteAddr = strings.Clone(r.RemoteAddr)
		next.ServeHTTP(w, owned)
	})
}

// headerMatcher forwards the browser's User-Agent under the key the gRPC server reads for sessions and audit
// (x-user-agent); Authorization and X-Forwarded-For are forwarded by grpc-gateway itself
func headerMatcher(key string) (string, bool) {
	if textproto.CanonicalMIMEHeaderKey(key) == "User-Agent" {
		return "x-user-agent", true
	}
	return runtime.DefaultHeaderMatcher(key)
}

type errorBody struct {
	Code    string            `json:"code"`
	Message string            `json:"message"`
	Fields  map[string]string `json:"fields,omitempty"`
}

// errorHandler answers {"error": {code, message, fields}}, like the hand-written HTTP handlers, with the HTTP
// status of the gRPC code (NotFound → 404, PermissionDenied → 403, FailedPrecondition → 400…)
func errorHandler(logger zerolog.Logger) runtime.ErrorHandlerFunc {
	return func(ctx context.Context, mux *runtime.ServeMux, m runtime.Marshaler, w http.ResponseWriter, r *http.Request, err error) {
		st, ok := status.FromError(err)
		if !ok {
			st = status.New(status.Code(err), err.Error())
		}
		body := errorBody{Code: "internal", Message: "Ocurrió un error inesperado. Inténtalo de nuevo."}
		found := false
		for _, d := range st.Details() {
			if detail, isDetail := d.(*commonv1.ErrorDetail); isDetail {
				body = errorBody{Code: detail.GetCode(), Message: detail.GetMessage(), Fields: detail.GetFields()}
				found = true
				break
			}
		}
		httpStatus := runtime.HTTPStatusFromCode(st.Code())
		// Errors raised by the gateway itself (unknown route, wrong verb, bad JSON) carry no ErrorDetail
		if !found {
			var routing *runtime.HTTPStatusError
			if errors.As(err, &routing) {
				httpStatus = routing.HTTPStatus
			}
			switch httpStatus {
			case http.StatusNotFound:
				body = errorBody{Code: "not_found", Message: "La ruta no existe."}
			case http.StatusMethodNotAllowed:
				body = errorBody{Code: "method_not_allowed", Message: "Método no permitido en esta ruta."}
			case http.StatusBadRequest:
				body = errorBody{Code: "invalid_request", Message: st.Message()}
			default:
				logger.Error().Err(err).Str("path", r.URL.Path).Msg("rest call failed")
			}
		}
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(httpStatus)
		raw, _ := json.Marshal(map[string]errorBody{"error": body})
		_, _ = w.Write(raw)
	}
}
