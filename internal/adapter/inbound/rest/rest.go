// Package rest serves the REST face of lt-edu-api: a grpc-gateway generated from rest/http.yaml that turns each
// HTTP call into a call to the gRPC server on the loopback, so REST and gRPC go through the same interceptors
// (session, client IP, rate limit, logging) and the same core services. It also serves the OpenAPI document and
// a Swagger UI page.
package rest

